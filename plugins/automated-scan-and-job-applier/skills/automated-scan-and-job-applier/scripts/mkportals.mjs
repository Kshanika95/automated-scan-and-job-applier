// Write career-ops's portals.yml from its template plus this workspace's search.json
// (title keywords for the zero-token scanner, and location allow/block lists).
// Usage: node mkportals.mjs   (run again whenever search.json changes)
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const W = process.env.JOB_APPLIER_HOME || path.dirname(fileURLToPath(import.meta.url));
const cfg = JSON.parse(fs.readFileSync(path.join(W, 'config.json'), 'utf8'));
const search = JSON.parse(fs.readFileSync(path.join(W, 'search.json'), 'utf8'));
let C = cfg.career_ops_dir || 'career-ops';
if (!path.isAbsolute(C)) C = path.join(W, C);
const yaml = createRequire(path.join(C, 'package.json'))('js-yaml');
const d = yaml.load(fs.readFileSync(path.join(C, 'templates/portals.example.yml'), 'utf8'));
d.title_filter = {
  positive: search.scan_keywords || [],
  negative: (search.scan_negative_keywords || []),
};
const loc = search.locations || {};
d.location_filter = {
  allow: [...(loc.remote ? ['Remote'] : []), ...(loc.scan_location_allow || []), ...(loc.onsite_keywords || []).map(s => s.replace(/\b\w/g, c => c.toUpperCase()))],
  block: loc.scan_location_block || [],
};
delete d.search_queries;
fs.writeFileSync(path.join(C, 'portals.yml'), `# Generated by automated-scan-and-job-applier from templates/portals.example.yml and search.json\n` + yaml.dump(d, { lineWidth: 200 }));
const tc = d.tracked_companies || [];
console.log(`portals.yml written: ${d.title_filter.positive.length} title keywords, ${tc.filter(c => c.enabled !== false).length} tracked companies`);
